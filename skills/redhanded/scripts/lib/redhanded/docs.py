"""Generate rule documentation from the registry, so docs never drift from the code."""

from __future__ import annotations

from typing import List

from .rules import RULES

CATEGORY_TITLE = {
    "tests": "Tests",
    "implementation": "Implementation",
    "config": "Configuration",
    "session": "Session (agent transcripts)",
}
CATEGORY_BLURB = {
    "tests": "Changes to the test suite that make it pass without the behaviour working.",
    "implementation": "Production code written to satisfy the tests rather than the requirement.",
    "config": "Configuration changes that redefine what counts as passing.",
    "session": "What the agent said and ran, read from its Claude Code transcript.",
}


def rules_markdown(heading: str = "# Rules") -> str:
    out: List[str] = [heading, "", "<!-- generated by `redhanded rules --format markdown`; do not edit by hand -->", ""]
    out.append("| Rule | Severity | What it flags |")
    out.append("|---|---|---|")
    for r in RULES:
        # A pipe ends a table cell even inside `code`, so escape it.
        out.append("| [`%s`](#%s) | %s | %s |" % (r.id, r.id, r.severity.label, r.summary.replace("|", "\\|")))
    current = None
    for r in RULES:
        if r.category != current:
            current = r.category
            out += ["", "## %s" % CATEGORY_TITLE.get(current, current.title()), "", CATEGORY_BLURB.get(current, "")]
        out += [
            "",
            "### %s" % r.id,
            "",
            "**%s** · default severity: **%s**" % (r.title, r.severity.label),
            "",
            "- **Flags:** %s" % r.summary,
            "- **Why it matters:** %s" % r.why,
            "- **What to do:** %s" % r.fix,
        ]
        if r.intent:
            out.append("- **Lowered to low** when the user's own request asks for this kind of change.")
    out.append("")
    return "\n".join(out)
